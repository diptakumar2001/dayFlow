"""Draws DayFlow's dark-mode background: a dark solar system (sun glow off the top-left corner, faint orbits,
Earth, Mars, Jupiter and Saturn lit only on the side facing the sun, sparse stars). Two compositions:
images/space-wide.svg (desktop) and images/space-tall.svg (phones). Run: python tools/make-space.py
"""
import math, pathlib, random

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Planet colours: (lit colour, mid colour)
EARTH = ("#7cc4e8", "#2f6f8f")
MARS = ("#e0896a", "#8a3f2e")
JUPITER = ("#e3c39a", "#9a7650")
SATURN = ("#e9d6a6", "#9c8a5e")
SHADOW = "#0b1022"


def on_orbit(sun, rx, ry, deg):
    t = math.radians(deg)
    return sun[0] + rx * math.cos(t), sun[1] + ry * math.sin(t)


def shade_defs(name, lit, mid, sun_dir):
    # The lit side faces the sun: move the gradient's bright spot towards it.
    fx = 0.5 - 0.32 * sun_dir[0]
    fy = 0.5 - 0.32 * sun_dir[1]
    return f"""
    <radialGradient id="{name}" cx="{fx:.2f}" cy="{fy:.2f}" r="0.75">
      <stop offset="0" stop-color="{lit}" stop-opacity="0.85"/>
      <stop offset="0.45" stop-color="{mid}" stop-opacity="0.75"/>
      <stop offset="1" stop-color="{SHADOW}"/>
    </radialGradient>"""


def planet(name, x, y, r, sun):
    dx, dy = x - sun[0], y - sun[1]
    n = math.hypot(dx, dy)
    return (x, y, r, name, (dx / n, dy / n))


def build(w, h, sun, orbits, planets, seed, file):
    random.seed(seed)
    defs, body = [], []
    # Stars: sparse, a little fewer in the middle where the planner sits
    stars = []
    while len(stars) < 46:
        x, y = random.uniform(0, w), random.uniform(0, h)
        mid = abs(x / w - 0.5) < 0.3 and abs(y / h - 0.5) < 0.3
        if mid and random.random() < 0.6:
            continue
        stars.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{random.uniform(0.6, 1.4):.1f}" '
                     f'fill="#dfe6ff" opacity="{random.uniform(0.25, 0.7):.2f}"/>')
    orbit_svg = [f'<ellipse cx="{sun[0]}" cy="{sun[1]}" rx="{rx}" ry="{ry}" fill="none" '
                 f'stroke="#aab9f0" stroke-opacity="0.10" stroke-width="1.2"/>' for rx, ry in orbits]
    for (x, y, r, kind, d) in planets:
        lit, mid = {"earth": EARTH, "mars": MARS, "jupiter": JUPITER, "saturn": SATURN}[kind]
        gid = f"g-{kind}"
        defs.append(shade_defs(gid, lit, mid, d))
        if kind == "saturn":
            # Ring: back half behind the planet, front half over it
            tilt = -18
            ring = f'rx="{r * 2.1:.1f}" ry="{r * 0.55:.1f}" fill="none" stroke="{lit}" stroke-width="{r * 0.16:.1f}"'
            body.append(f'<g transform="rotate({tilt} {x:.0f} {y:.0f})"><ellipse cx="{x:.0f}" cy="{y:.0f}" {ring} '
                        f'stroke-opacity="0.18"/></g>')
        body.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{r}" fill="url(#{gid})"/>')
        if kind == "jupiter":
            # Faint bands, clipped to the planet, under the same shading
            defs.append(f'<clipPath id="clip-j"><circle cx="{x:.0f}" cy="{y:.0f}" r="{r}"/></clipPath>')
            bands = "".join(
                f'<rect x="{x - r:.0f}" y="{y + o * r:.0f}" width="{2 * r}" height="{r * 0.16:.1f}" '
                f'fill="#2a1d14" opacity="0.35"/>' for o in (-0.55, -0.2, 0.15, 0.5))
            body.append(f'<g clip-path="url(#clip-j)">{bands}</g>')
        if kind == "saturn":
            path = (f'M {x - r * 2.1:.1f} {y:.0f} A {r * 2.1:.1f} {r * 0.55:.1f} 0 0 0 {x + r * 2.1:.1f} {y:.0f}')
            body.append(f'<g transform="rotate({tilt} {x:.0f} {y:.0f})"><path d="{path}" fill="none" '
                        f'stroke="{lit}" stroke-opacity="0.32" stroke-width="{r * 0.16:.1f}"/></g>')
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" preserveAspectRatio="xMidYMid slice">
  <!-- DayFlow dark-mode background: a dark solar system. Generated by tools/make-space.py -->
  <defs>
    <radialGradient id="space" cx="0.55" cy="0.5" r="0.75">
      <stop offset="0" stop-color="#0d1533"/>
      <stop offset="1" stop-color="#050816"/>
    </radialGradient>
    <radialGradient id="haze" cx="0.5" cy="0.6" r="0.5">
      <stop offset="0" stop-color="#5b4aa8" stop-opacity="0.12"/>
      <stop offset="1" stop-color="#5b4aa8" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="sun" cx="{sun[0]}" cy="{sun[1]}" r="{max(w, h) * 0.55:.0f}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#ffd696" stop-opacity="0.36"/>
      <stop offset="0.3" stop-color="#ffbe82" stop-opacity="0.12"/>
      <stop offset="1" stop-color="#ffbe82" stop-opacity="0"/>
    </radialGradient>{"".join(defs)}
  </defs>
  <rect width="{w}" height="{h}" fill="url(#space)"/>
  <rect width="{w}" height="{h}" fill="url(#haze)"/>
  {"".join(stars)}
  <rect width="{w}" height="{h}" fill="url(#sun)"/>
  {"".join(orbit_svg)}
  {"".join(body)}
</svg>
"""
    out = ROOT / "images" / file
    out.parent.mkdir(exist_ok=True)
    out.write_text(svg, encoding="utf-8")
    print("Wrote", out, round(out.stat().st_size / 1024, 1), "KB")


# Wide (desktop): planets at the edges and corners, around where the panels sit.
sun = (-90, -70)
orbits = [(470, 385), (760, 623), (1120, 918), (1520, 1246)]
build(1600, 1000, sun, orbits, [
    planet("earth", *on_orbit(sun, 470, 385, 70), 16, sun),
    planet("mars", *on_orbit(sun, 760, 623, 14), 13, sun),
    planet("jupiter", *on_orbit(sun, 1120, 918, 68), 34, sun),
    planet("saturn", *on_orbit(sun, 1520, 1246, 36), 24, sun),
], 5, "space-wide.svg")

# Tall (phones): Earth upper-left, Mars upper-right, Jupiter right edge, Saturn low on the left.
sun = (-70, -60)
orbits = [(380, 437), (640, 736), (980, 1127), (1400, 1610)]
build(900, 1950, sun, orbits, [
    planet("earth", *on_orbit(sun, 380, 437, 55), 17, sun),
    planet("mars", *on_orbit(sun, 640, 736, 8), 14, sun),
    planet("jupiter", *on_orbit(sun, 980, 1127, 30), 36, sun),
    planet("saturn", *on_orbit(sun, 1400, 1610, 75), 27, sun),
], 9, "space-tall.svg")
